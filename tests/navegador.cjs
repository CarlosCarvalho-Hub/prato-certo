// Com Playwright instalado para testes: node tests/navegador.cjs URL
// NAVEGADOR pode apontar para um Chrome/Edge local. AXE_JS é opcional.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const url = process.argv[2] || 'http://localhost:8000/'
const origem = new URL(url).origin

async function testar() {
  const browser = await chromium.launch({ executablePath: process.env.NAVEGADOR || undefined })
  try {
    const contexto = await browser.newContext({ reducedMotion: 'reduce', locale: 'pt-BR',
      viewport: { width: 1440, height: 960 } })
    const pagina = await contexto.newPage()
    const erros = []
    pagina.on('pageerror', e => erros.push(e.message))
    pagina.on('response', r => { if (r.status() >= 400) erros.push(r.status() + ' ' + r.url()) })
    const el = s => pagina.locator(s)
    const clique = s => el(s).click()
    const chip = id => clique('[data-valor="' + id + '"]')
    const cartoes = el('[data-cartoes] article')
    const salvos = el('[data-favoritos] article')
    const registros = el('[data-historico] > li')
    const gerar = () => clique('[data-gerar]')
    const dados = () => pagina.evaluate(() => JSON.stringify(localStorage))
    const marcar = nome => console.log('OK · ' + nome)
    async function abrir() {
      await pagina.goto(url)
      await el('[data-valor="vegano"]').waitFor()
      await pagina.evaluate(() => document.fonts.ready)
    }
    async function acessibilidade(tema) {
      if (!process.env.AXE_JS) return
      await pagina.addScriptTag({ path: process.env.AXE_JS })
      const falhas = await pagina.evaluate(async () => (await axe.run(document, {
        runOnly: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']
      })).violations.map(f => [f.id, f.nodes.slice(0,3).map(n => n.target)]))
      assert.deepEqual(falhas, [], tema)
      marcar('auditoria automatizada de acessibilidade · ' + tema)
    }
    await abrir()
    assert.equal(await el('[data-linhas] tr').count(), 40)
    const precos = (await el('td.tabela__preco').allTextContents()).map(s => Number(s.replace(/[^\d,]/g,'').replace(',','.')))
    assert.deepEqual(precos, [...precos].sort((a,b) => a-b))
    await pagina.keyboard.press('Tab')
    assert.equal(await pagina.locator(':focus').getAttribute('href'), '#conteudo')
    await pagina.keyboard.press('Enter')
    assert.equal(await pagina.locator(':focus').getAttribute('id'), 'conteudo')
    await el('[data-valor="vegano"]').focus()
    await pagina.keyboard.press('Space')
    assert.equal(await el('[data-valor="vegano"]').getAttribute('aria-pressed'),'true')
    await gerar()
    assert.equal(await cartoes.count(), 3)
    const primeiro = await cartoes.locator('h3').allTextContents()
    assert.ok((await cartoes.locator('.selos').allTextContents()).every(s => s.includes('Vegano')))
    await gerar()
    assert.notDeepEqual(await cartoes.locator('h3').allTextContents(), primeiro)
    await el('[data-cartoes] [data-favorito]').first().click()
    assert.equal(await salvos.count(), 1)
    marcar('preço, teclado, três sugestões, variação e favorito')
    await chip('italiana')
    assert.equal(await cartoes.count(),0)
    await gerar()
    assert.equal(await cartoes.count(),1)
    assert.match(await cartoes.innerText(),/Espaguete ao pomodoro/)
    await chip('sem_gluten')
    assert.equal(await cartoes.count(), 0)
    assert.ok(await el('[data-gerar]').isDisabled())
    assert.ok(await el('[data-vazio]').isVisible())
    await chip('sem_gluten')
    await chip('italiana')
    await chip('japonesa')
    await gerar()
    assert.equal(await cartoes.count(), 2)
    marcar('zero, uma e duas opções compatíveis, sem completar com pratos incompatíveis')
    await clique('[data-limpar]')
    assert.equal(await el('[data-linhas] tr').count(),40)
    await clique('[data-limpar]')
    assert.equal(await el('[data-linhas] tr').count(),2)
    await chip('distancia')
    assert.equal(await pagina.locator(':focus').getAttribute('id'),'onde')
    await el('#onde').selectOption({label:'Asa Sul'})
    assert.equal(await el('th[aria-sort]').getAttribute('data-coluna'),'distancia')
    await chip('restaurante')
    assert.equal(await el('th[aria-sort]').getAttribute('data-coluna'),'restaurante')
    await gerar()
    const antes = await registros.allTextContents()
    await acessibilidade('escuro')
    await clique('button[data-tema]')
    await pagina.reload()
    await el('[data-valor="japonesa"]').waitFor()
    assert.equal(await el('html').getAttribute('data-tema'),'claro')
    assert.equal(await el('#onde').inputValue(),'Asa Sul')
    assert.equal(await el('[data-valor="vegano"]').getAttribute('aria-pressed'),'true')
    assert.equal(await el('[data-valor="japonesa"]').getAttribute('aria-pressed'),'true')
    assert.equal(await el('th[aria-sort]').getAttribute('data-coluna'),'restaurante')
    assert.equal(await salvos.count(),1)
    assert.deepEqual(await registros.allTextContents(),antes)
    const outraAba = await contexto.newPage()
    await outraAba.goto(url)
    await outraAba.locator('[data-favoritos] article').waitFor()
    await outraAba.locator('button[data-tema]').click()
    await pagina.waitForFunction(() => document.documentElement.dataset.tema === 'escuro')
    await outraAba.locator('button[data-tema]').click()
    await pagina.waitForFunction(() => document.documentElement.dataset.tema === 'claro')
    await outraAba.close()
    marcar('leitura em outra aba e sincronização do tema')
    await gerar()
    await acessibilidade('claro')
    await el('[data-favoritos] button').click()
    await pagina.reload()
    await el('[data-valor="japonesa"]').waitFor()
    assert.equal(await salvos.count(),0)
    marcar('limpar e desfazer, bairro, três ordenações e persistência após recarga')
    await contexto.grantPermissions(['geolocation'],{origin:origem})
    await contexto.setGeolocation({latitude:-15.797123,longitude:-47.887123})
    await clique('[data-localizar]')
    await pagina.waitForFunction(() => document.querySelector('#onde').value === 'aqui')
    assert.doesNotMatch(await dados(),/-15\.797123|-47\.887123|latitude|longitude/)
    await clique('[data-limpar]')
    await gerar()
    for (const largura of [320,375,768,1280,1920]) {
      await pagina.setViewportSize({width:largura,height:850})
      const cabe = await pagina.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
      assert.ok(cabe, 'largura ' + largura)
    }
    marcar('localização simulada autorizada, privacidade e cinco larguras')
    pagina.once('dialog', caixa => caixa.dismiss())
    await clique('[data-apagar]')
    assert.ok(await registros.count() > 0)
    pagina.once('dialog', caixa => caixa.accept())
    await clique('[data-apagar]')
    assert.equal(await registros.count(),0)
    assert.equal(await el('html').getAttribute('data-tema'),'escuro')
    await pagina.reload()
    await el('[data-valor="vegano"]').waitFor()
    assert.equal(await dados(),'{}')
    const prefixo = 'pratocerto:' + new URL('.',url).pathname + ':'
    await pagina.evaluate(prefixo => {
      localStorage.setItem(prefixo + 'escolhas','{')
      localStorage.setItem(prefixo + 'historico','[null,17,{"ids":[500]}]')
      localStorage.setItem(prefixo + 'favoritos','["nome",900]')
      localStorage.setItem('exemplo-de-outro-site','preservar')
    }, prefixo)
    await abrir()
    assert.equal(await el('[data-linhas] tr').count(),40)
    assert.equal(await registros.count(),0)
    assert.equal(await salvos.count(),0)
    pagina.once('dialog', caixa => caixa.accept())
    await clique('[data-apagar]')
    assert.equal(await pagina.evaluate(() => localStorage.getItem('exemplo-de-outro-site')), 'preservar')
    marcar('recuperação de dados inválidos e limpeza restrita à instalação')
    // Falhas de permissão e de armazenamento são determinísticas nesta aba isolada.
    await pagina.addInitScript(() => {
      Object.defineProperty(navigator, 'geolocation', {value:{
        getCurrentPosition: (_, erro) => erro({code:1, PERMISSION_DENIED:1})
      }})
      Storage.prototype.setItem = () => { throw new Error('Armazenamento bloqueado') }
    })
    await abrir()
    await clique('[data-localizar]')
    assert.match(await el('[data-dica-local]').innerText(),/Sem permissão/)
    await el('#onde').selectOption('Asa Sul')
    await chip('vegano')
    await gerar()
    await el('[data-cartoes] button').first().click()
    assert.equal(await salvos.count(),1)
    assert.ok(await el('[data-aviso-memoria]').isVisible())
    assert.match(await el('td.tabela__distancia').first().innerText(),/m/)
    await pagina.goto(new URL('entrar.html',url).href)
    await el('[data-sem-login]').waitFor()
    assert.deepEqual(erros, [])
    marcar('cancelar e confirmar exclusão, modo sem conta, permissão negada e memória bloqueada')
    console.log('Navegador ' + browser.version())
  } finally { await browser.close() }
}
testar().catch(erro => { console.error(erro); process.exitCode = 1 })
